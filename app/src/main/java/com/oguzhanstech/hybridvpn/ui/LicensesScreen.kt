/**
 * The app's licence (GPL-3.0-or-later) and the notices of every bundled component, from assets
 * generated by scripts/gen-notices.py. Paragraphs are lazy items: the texts are ~150 KB.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun LicensesScreen(onBack: () -> Unit) {
    val context = LocalContext.current
    var paragraphs by remember { mutableStateOf<List<String>>(emptyList()) }
    LaunchedEffect(Unit) {
        paragraphs = withContext(Dispatchers.IO) {
            listOf(APP_NOTICE) + listOf("third_party_licenses.txt", "gpl-3.0.txt").flatMap { name ->
                runCatching { context.assets.open(name).bufferedReader().use { it.readText() } }
                    .getOrElse { "($name is missing from this build)" }
                    .split(Regex("\n\\s*\n"))
            }
        }
    }
    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Open-source licences") },
                navigationIcon = { IconButton(onClick = onBack) { Icon(Icons.AutoMirrored.Filled.ArrowBack, "Back") } },
            )
        },
    ) { padding ->
        LazyColumn(Modifier.fillMaxSize().padding(padding).padding(horizontal = 16.dp)) {
            items(paragraphs) { p ->
                Text(
                    p.trim('\n'),
                    Modifier.padding(vertical = 6.dp),
                    style = MaterialTheme.typography.bodySmall,
                    fontFamily = if (p.startsWith("====")) null else FontFamily.Monospace,
                )
            }
        }
    }
}

